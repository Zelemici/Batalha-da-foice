import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import '../v10-core.js';
import '../archive-2026.js';
import '../history-2026.js';

const original=JSON.parse(readFileSync(new URL('../data.json',import.meta.url),'utf8'));
const apply=globalThis.BDFHistory.apply;
const core=globalThis.BDFV10Core;
const archive=globalThis.BDFArchive;
const originalTotals=new Map(original.data.map(m=>[m.id,core.titleCount(m)]));
const next=apply(original);
const get=name=>next.data.find(m=>archive.canonical(m.name)===archive.canonical(name));
const cfg=next.cfg.v10,editions=cfg.editionArchive.catalog;
const byNo=n=>editions[n-1];
const memberWins=(name)=>get(name).archiveEditionIds.map(x=>x.number);
assert.equal(original.data.length,29,'Cadastro-base original permanece com 29 MCs');
assert.equal(editions.length,194,'Todos os números #1 a #194 são registrados');
assert(editions.every((e,i)=>e.number===i+1),'Números de edição em ordem, sem saltos artificiais');
assert.equal(byNo(3).status,'campeão não identificado','Edição desconhecida não ganha campeão inventado');
assert.equal(byNo(11).claims[0].names[0],'Japa','A edição #11 é de Japa');
assert.equal(byNo(7).claims[0].names[0],'Maldonado','Antiga atribuição errada de #7 deve ser corrigida');
assert.equal(byNo(146).claims.length,2,'#146 preserva duas anotações');
assert(byNo(146).conflict,'#146 fica sinalizada para conferência, sem supor dupla');
assert.equal(byNo(92).claims[0].format,'dupla');
assert.equal(byNo(93).claims[0].format,'dupla');
assert.equal(byNo(173).claims[0].format,'dupla');
assert.equal(byNo(177).claims[0].format,'dupla');
assert.equal(byNo(193).claims[0].format,'dupla');
assert.equal(byNo(188).year,2026);
assert.equal(byNo(189).year,null,'Não inferir ano da última sequência sem cabeçalho final');
assert.equal(byNo(179).special.id,'oldnew');
assert.equal(byNo(127).special.id,'oldnew');
assert.equal(byNo(110).special.id,'regional');
assert.equal(byNo(167).special.id,'regional');
assert.equal(byNo(178).special.id,'regional');
assert.equal(byNo(188).special.id,'baile');
assert.equal(byNo(103).special.id,'baile');
assert.equal(byNo(150).claims[0].names[0],'Zel');
assert.deepEqual(memberWins('Zel').sort((a,b)=>a-b),[150,155,161,163,173,174,179]);
for(const m of original.data)assert.equal(core.titleCount(next.data.find(x=>x.id===m.id)),originalTotals.get(m.id),'Títulos originais preservados: '+m.name);
for(const [n,t] of [['Vieira Zr',81],['Jotapê',34],['Zel',7],['R10',30],['Dia',5],['Quintanilha',2]])assert.equal(core.titleCount(get(n)),t,'Não somar conquistas documentadas a '+n);
assert(next.data.some(m=>m.archiveEditionIds?.some(e=>e.special==='New vs Old School')));
const allIds=next.data.map(m=>m.id);
assert.equal(new Set(allIds).size,allIds.length,'Sem IDs de MC duplicados');
assert.equal(new Set(next.data.map(m=>archive.canonical(m.name))).size,next.data.length,'Sem MCs duplicados por nome / apelido normalizado');
assert(next.data.some(m=>m.name==='Pelé'&&core.titleCount(m)===0),'Adversário não recebe título');
assert(next.data.some(m=>m.name==='Magnata'&&core.titleCount(m)===0),'Finalista sem título informado entra com zero');
assert.equal(byNo(193).claims[0].mcIds.length,2,'Dupla gera um vínculo para cada integrante');
assert(memberWins('Gaab').includes(193));
assert(memberWins('Jamal').includes(193));
const duels=cfg.manualDuels;
assert.equal(duels.filter(x=>x.id.startsWith('arc26-')).length,archive.direct.length,'Cada resultado individual explícito aparece uma vez');
assert(duels.every(x=>x.score==='Outro'&&x.date===''),'Não inventar datas e placares');
assert.equal(core.duelHistory(get('Zel'),get('Antares'),[],duels,next.data).a,3,'#150, #161 e #174: vitórias individuais de Zel sobre Antares');
assert.equal(core.duelHistory(get('J²'),get('Audaz'),[],duels,next.data).a,1,'Confronto de #165');
assert.equal(core.duelHistory(get('Mont'),get('Frazão'),[],duels,next.data).a,1,'Final de #135');
assert.equal(core.duelHistory(get('Zel'),get('Jotapê'),[],duels,next.data).matches.length,0,'Final tripla #150 não vira dois duelos 1×1');
assert.equal(cfg.editionArchive.teamMatches.filter(x=>x.edition===173).length,3,'Confrontos em dupla são preservados sem 1×1 fictícios');
assert.equal(cfg.editionArchive.specialUnnumbered[0].mcId,get('Vieira Zr').id,'Regional de Vieira sem número explícito');
assert.deepEqual(core.validateV10(next),[],'Todos os cadastros e partidas continuam validáveis');
const again=apply(next);
assert.equal(again.data.length,next.data.length,'Segunda importação não cria novos perfis');
assert.equal(again.cfg.v10.manualDuels.length,next.cfg.v10.manualDuels.length,'Segunda importação não cria novas vitórias');
assert.equal(core.titleCount(again.data.find(x=>x.id===get('Zel').id)),7,'Segunda importação não soma títulos');
assert.equal(again.cfg.v10.editionArchive.catalog.length,194);
const duplicate=apply({data:[{id:'already',name:'MC Jeffinho',titles:{2022:2}}],cfg:{}});
assert.equal(duplicate.data.filter(m=>archive.canonical(m.name)==='Jeffinho').length,1,'MC Jeffinho vira Jeffinho sem duplicar');
assert.equal(core.titleCount(duplicate.data.find(x=>x.id==='already')),2,'Contagem diferente deve ser preservada');
const ui=readFileSync(new URL('../archive-ui.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../archive-ui.css',import.meta.url),'utf8');
const index=readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert(index.includes('<script src="archive-2026.js"></script>'));
assert(index.includes('<script src="archive-ui.js"></script>'));
assert(index.includes('<link rel="stylesheet" href="archive-ui.css">'));
assert(ui.includes('Campeões de edições especiais')&&ui.includes('Hall dos Campeões'));
assert(ui.includes('data-arc-category')&&ui.includes('data-arc-show'));
assert(css.includes('.arc-chip-regional')&&css.includes('.arc-chip-oldnew'));
assert(css.includes('@media(max-width:650px)'),'Visual responsivo');
