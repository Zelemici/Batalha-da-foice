console.log('CONTAGENS PARA CONCILIAR: '+next.data.filter(m=>(m.archiveEditionIds||[]).some(x=>x.status==='conferir')).map(m=>m.name+': '+m.archiveEditionIds.filter(x=>x.status==='conferir').map(x=>'#'+x.number).join(',')).join(' | '));
