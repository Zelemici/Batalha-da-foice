import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import '../v10-core.js';
import '../history-2026.js';

const original=JSON.parse(readFileSync(new URL('../data.json',import.meta.url),'utf8'));
const apply=globalThis.BDFHistory.apply;
const count=globalThis.BDFV10Core.titleCount;
const oldNames=original.data.map(m=>m.name);
const oldCounts=new Map(original.data.map(m=>[m.id,count(m)]));
const next=apply(original);
const find=name=>next.data.find(m=>m.name.toLowerCase()===name.toLowerCase());
assert.equal(next.data.length,original.data.length+20,'18 campeões novos + 2 oponentes sem título');
assert.equal(count(find('Vieira Zr')),81,'Não somar as cinco edições aos 81 títulos');
assert.deepEqual(find('Vieira Zr').historicEditions,['#53','#54','#55','#56','#57']);
assert.equal(count(find('Dia')),5,'As três edições não mudam os cinco títulos');
assert.deepEqual(find('Dia').historicEditions,['#11','#20','#58']);
assert.equal(count(find('R10')),30,'As duas edições não mudam os 30 títulos');
assert.equal(count(find('BOB')),7);
assert.equal(count(find('Brandon')),2);
assert.deepEqual(find('Son').historicEditions,['#45','#70'],'Não inventar a terceira edição do Son');
assert.equal(find('Pelé').photo,'');
assert.equal(count(find('Pelé')),0);
assert.equal(find('JR').aliases.includes('Jr Final'),true);
assert.equal(find('R10').aliases.includes('Verissimo'),true);
for(const old of original.data)assert.equal(count(next.data.find(x=>x.id===old.id)),oldCounts.get(old.id),'Preservar títulos já existentes de '+old.name);
assert.deepEqual(globalThis.BDFV10Core.validateV10(next),[],'Dados históricos devem cumprir as regras de publicação');
const duels=next.cfg.v10.manualDuels;
assert.equal(duels.length,8,'Seis chaves parciais e oito confrontos documentados');
assert(duels.every(x=>x.score==='Outro'&&x.date===''),'Não inventar placares ou datas');
assert.equal(globalThis.BDFV10Core.duelHistory(find('Naan'),find('Dia'),[],duels,next.data).a,1);
assert.equal(globalThis.BDFV10Core.duelHistory(find('JR'),find('Japa'),[],duels,next.data).a,1);
assert.equal(globalThis.BDFV10Core.duelHistory(find('Mad Dog'),find('Jaime'),[],duels,next.data).a,1);
assert.equal(globalThis.BDFV10Core.duelHistory(find('R10'),find('Jaime'),[],duels,next.data).a,1);
assert.equal(next.cfg.v10.historicalBrackets.length,6);
const again=apply(next);
assert.equal(again.data.length,next.data.length,'Importação idempotente: sem duplicar MCs');
assert.equal(again.cfg.v10.manualDuels.length,8,'Importação idempotente: sem duplicar confrontos');
assert.equal(again.cfg.v10.historicalBrackets.length,6,'Importação idempotente: sem duplicar chaves');
assert.deepEqual(again.data.find(m=>m.id===find('Vieira Zr').id).historicEditions,find('Vieira Zr').historicEditions);
const other=apply({data:[{id:'existing',name:'MC Jeffinho',titles:{2022:2}}],cfg:{}});
assert.equal(other.data.filter(m=>m.name==='Jeffinho'||m.name==='MC Jeffinho').length,1,'Reutilizar apelidos com prefixo MC');
assert.equal(count(other.data.find(m=>m.id==='existing')),2,'Cadastro existente preservado mesmo com contagem diferente');
console.log('Histórico de campeões: 20 novos cadastros, edições e 8 confrontos validados.');
